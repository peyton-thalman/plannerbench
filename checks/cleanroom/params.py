# Rounding helpers (RULES.md 0.2). A tiny epsilon keeps binary floating point from flipping exact multiples.
# ---------------------------------------------------------------------------------------------------------
EPS = 1e-9


def floor_to(x, u):
    """Largest multiple of u that is <= x."""
    return round(math.floor(x / u + EPS) * u, 10)


def round_to(x, u):
    """Nearest multiple of u, halves rounded up."""
    return round(math.floor(x / u + 0.5 + EPS) * u, 10)


