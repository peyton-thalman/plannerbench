class Params:
    """Parameter lookups by year with RULES Section 14 projection.

    `get(name, year)` returns the value for `year` (by filing status inside, where the parameter has one) and
    records the year in `projected_years` when the value was projected rather than published.
    """

    def __init__(self, inflation=0.025, chained_cpi_gap=0.0, cola=None, medicare_growth=None, overrides=None):
        self.inflation = inflation
        self.chained = inflation - chained_cpi_gap           # RULES 1.6: chained CPI growth
        self.cola = inflation if cola is None else cola     # RULES 1.6
        self.medicare_growth = inflation if medicare_growth is None else medicare_growth
        self.overrides = dict(overrides or {})
        self.projected_years = set()

    # -- bookkeeping --------------------------------------------------------------------------------------
    def reset_tracking(self):
        self.projected_years = set()

    def _mark(self, year):
        self.projected_years.add(year)

    def const(self, name):
        if name in self.overrides:
            v = self.overrides[name]
            return v(None) if callable(v) else v
        return CONSTANTS[name]

    def get(self, name, year):
        if name in self.overrides:
            v = self.overrides[name]
            return v(year) if callable(v) else v
        fn = getattr(self, "_" + name, None)
        if fn is not None:
            return fn(year)
        return CONSTANTS[name]

    # -- projection helpers (RULES 14.1) ------------------------------------------------------------------
    def _chain(self, table, year, growth):
        """Return (seed_value, n_years, projected) for a published-by-year table."""
        years = sorted(table)
        if year in table:
            return table[year], 0, False
        if year < years[0]:
            return table[years[0]], 0, False  # before the table: earliest published value (not used in scope)
        last = years[-1]
        return table[last], year - last, True

    # -- federal income tax -------------------------------------------------------------------------------
    def _ordinary_brackets(self, year):
        seed, n, proj = self._chain(PUBLISHED["ordinary_brackets"], year, self.chained)
        if not proj:
            return seed
        self._mark(year)
        out = {}
        for filing, brackets in seed.items():
            unit = CONSTANTS["bracket_rounding"][filing]
            out[filing] = [(None if up is None else floor_to(up * (1 + self.chained) ** n, unit), rate)
                           for up, rate in brackets]
        return out

    def _bracket37_start(self, year):
        b = self.get("ordinary_brackets", year)
        return {f: [up for up, rate in v if up is not None][-1] for f, v in b.items()}

    def _cg_thresholds(self, year):
        seed, n, proj = self._chain(PUBLISHED["cg_thresholds"], year, self.chained)
        if not proj:
            return seed
        self._mark(year)
        g = (1 + self.chained) ** n
        return {f: {k: floor_to(v * g, 50) for k, v in d.items()} for f, d in seed.items()}

    def _standard_deduction(self, year):
        seed, n, proj = self._chain(PUBLISHED["standard_deduction"], year, self.chained)
        if not proj:
            return seed
        self._mark(year)
        g = (1 + self.chained) ** n
        return {f: floor_to(v * g, 50) for f, v in seed.items()}

    def _additional_std_65(self, year):
        seed, n, proj = self._chain(PUBLISHED["additional_std_65"], year, self.chained)
        if not proj:
            return seed
        self._mark(year)
        g = (1 + self.chained) ** n
        return {k: floor_to(v * g, 50) for k, v in seed.items()}

    def _qcd_limit(self, year):
        seed, n, proj = self._chain(PUBLISHED["qcd_limit"], year, self.chained)
        if not proj:
            return seed
        self._mark(year)
        return round_to(seed * (1 + self.chained) ** n, 1000)

    def _salt(self, year):
        """{'cap', 'threshold', 'phasedown'} — statutory schedule (RULES 14.2), never 'projected'."""
        if year in SALT_FIXED:
            d = SALT_FIXED[year]
            return {"cap": d["cap"], "threshold": d["threshold"], "phasedown": True}
        if year < 2025:
            d = SALT_FIXED[2025]
            return {"cap": d["cap"], "threshold": d["threshold"], "phasedown": True}
        if year <= CONSTANTS["salt_phasedown_last_year"]:
            f = 1.01 ** (year - 2026)
            return {"cap": SALT_FIXED[2026]["cap"] * f, "threshold": SALT_FIXED[2026]["threshold"] * f,
                    "phasedown": True}
        return {"cap": float(CONSTANTS["salt_cap_permanent"]), "threshold": None, "phasedown": False}

    # -- Social Security ----------------------------------------------------------------------------------
    def _earnings_limit(self, table, year):
        """RULES 5.8 (v1.4.1): published for 2025 and 2026; later years grow with inflation from 2026, nearest $120."""
        seed, n, proj = self._chain(table, year, self.inflation)
        if not proj:
            return seed
        self._mark(year)
        return round_to(seed * (1 + self.inflation) ** n, 120)

    def _ss_earnings_under(self, year):
        return self._earnings_limit(PUBLISHED["ss_earnings_under"], year)

    def _ss_earnings_fra_year(self, year):
        return self._earnings_limit(PUBLISHED["ss_earnings_fra_year"], year)

    def _ss_cola(self, year):
        t = PUBLISHED["ss_cola"]
        if year in t:
            return t[year]
        if year < min(t):
            return t[min(t)]
        self._mark(year)
        return self.cola

    # -- Medicare (RULES 12.3-12.5, 14.2) ------------------------------------------------------------------
    def _irmaa_bounds(self, year):
        """{'single': [u0,u1,u2,u3,top], 'mfj': [...]}: tier 0 if M <= u0; tier k (1-3) if u_{k-1} < M <= u_k;
        tier 4 if u3 < M < top; tier 5 if M >= top."""
        seed, n, proj = self._chain(PUBLISHED["irmaa_single_uppers"], year, self.inflation)
        if proj:
            self._mark(year)
            single = [round_to(u * (1 + self.inflation) ** n, 1000) for u in seed]
        else:
            single = list(seed)
        frozen = CONSTANTS["irmaa_top_frozen_through"]
        tops = {}
        for f, top in CONSTANTS["irmaa_top"].items():
            if year <= frozen:
                tops[f] = float(top)
            else:
                self._mark(year)
                tops[f] = round_to(top * (1 + self.inflation) ** (year - frozen), 1000)
        return {"single": single + [tops["single"]], "mfj": [2 * u for u in single] + [tops["mfj"]]}

    def _part_b_monthly(self, year):
        seed, n, proj = self._chain(PUBLISHED["part_b_monthly"], year, self.medicare_growth)
        if not proj:
            return list(seed)
        self._mark(year)
        std_unrounded = seed[0] * (1 + self.medicare_growth) ** n
        return [round_to(std_unrounded * (v / seed[0]), 0.1) for v in seed]

    def _part_d_irmaa_monthly(self, year):
        seed, n, proj = self._chain(PUBLISHED["part_d_irmaa_monthly"], year, self.medicare_growth)
        if not proj:
            return list(seed)
        self._mark(year)
        return [round_to(v * (1 + self.medicare_growth) ** n, 0.1) for v in seed]

    # -- Arizona ------------------------------------------------------------------------------------------
    def _az_standard_deduction(self, year):
        """RULES 10.2 v1.2: equal to the federal basic standard deduction (published or projected) every year;
        Arizona years from 2026 are labelled projected until ADOR publishes its forms."""
        value = dict(self.get("standard_deduction", year))
        if year > max(PUBLISHED["az_standard_deduction"]):
            self._mark(year)
        return value

    def _az_charitable_std_increase_rate(self, year):
        t = PUBLISHED["az_charitable_std_increase_rate"]
        return t.get(year, t[max(t)])
