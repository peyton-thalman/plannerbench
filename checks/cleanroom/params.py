# Social Security full retirement ages in months by birth year (other.json ss_full_retirement_age_*, from
# 20 CFR 404.409(a) and (b)). Everyone is born on the 15th (RULES 1.1), so the Jan-1 edge never arises.
def ss_fra_months(born):
    if born <= 1937:
        return 780
    if born <= 1942:
        return 780 + 2 * (born - 1937)
    if born <= 1954:
        return 792
    if born <= 1959:
        return 792 + 2 * (born - 1954)
    return 804


